def _document_text(document: DocxDocument) -> str:
    parts = [paragraph.text for paragraph in document.paragraphs]
    for table in document.tables:
        parts.extend(cell.text for row in table.rows for cell in row.cells)
    for section in document.sections:
        parts.extend(paragraph.text for paragraph in section.header.paragraphs)
        parts.extend(paragraph.text for paragraph in section.footer.paragraphs)
    return "\n".join(parts)


def test_report_date_format_is_locale_stable() -> None:
    assert format_report_date("2026-10-08", "id") == "08 Oktober 2026"
    assert format_report_date("2026-10-08", "en") == "October 8, 2026"
    assert format_report_date("October 8, 2026", "id") == "08 Oktober 2026"


def test_severity_compliance_and_workflow_status_are_localized() -> None:
    assert translate_severity("CRITICAL", "id") == "Kritis"
    assert translate_severity("INFO", "id") == "Informasi"
    assert translate_severity("MAJOR", "en") == "Major"
    assert translate_status("NON_COMPLIANT", "id") == "Tidak Sesuai"
    assert translate_status("NOT_APPLICABLE", "id") == "Tidak Berlaku"
    assert translate_status("VERIFIED_BY_LEAD", "id") == "Diverifikasi oleh Penanggung Jawab"
    assert get_report_labels("id")["table"]["reference_clause"] == "Klausul Acuan"


def test_legacy_score_banner_is_localized_at_render_time() -> None:
    localized = localize_review_score(
        "REVIEWSCORE | doc=DOC-42 | rev=C | date=2026-10-08 | "
        "I=4.00 II=3.25 III=2.50 IV=4.12 | baseline=3/4 | "
        "blockers=2 majors=5 minors=7",
        "id",
    )
    assert "NILAI TINJAUAN" in localized
    assert "dokumen=DOC-42" in localized
    assert "tanggal=2026-10-08" in localized
    assert "REVIEWSCORE" not in localized
    assert "baseline=" not in localized


def test_indonesian_docx_localizes_metadata_score_and_footer() -> None:
    assessment = create_canonical_ale_assessment_data()
    assessment.metadata.project_number = "13726486.01"
    assessment.metadata.client_name = "PT Contoh"
    assessment.metadata.document_date = "2026-10-08"
    assessment.metadata.review_date = "2026-10-08"
    report_bytes = generate_ale_review_docx(
        assessment,
        language=ReportLanguage.INDONESIAN,
    )
    rendered = docx.Document(io.BytesIO(report_bytes))
    text = _document_text(rendered)
    footer = "\n".join(paragraph.text for paragraph in rendered.sections[0].footer.paragraphs)

    for expected in (
        "Judul Laporan",
        "Nomor Proyek",
        "13726486.01",
        "Klien",
        "Tanggal Audit",
        "08 Oktober 2026",
        "Versi Dokumen",
        "NILAI TINJAUAN",
        "Disiapkan Oleh",
        "Ditinjau Oleh",
        "Disetujui Oleh",
    ):
        assert expected in text
    assert "Dibuat otomatis oleh PRISM" in footer
    assert "DOKUMEN RAHASIA" in footer
    assert "Halaman" in footer
    assert " dari " in footer
    assert "REVIEWSCORE" not in text
    assert "N/A" not in text
    assert "Page " not in footer
    assert " of " not in footer


def test_english_docx_keeps_english_footer_and_date() -> None:
    assessment = create_canonical_ale_assessment_data()
    assessment.metadata.document_date = "2026-10-08"
    assessment.metadata.review_date = "2026-10-08"
    rendered = docx.Document(
        io.BytesIO(generate_ale_review_docx(assessment, language=ReportLanguage.ENGLISH))
    )
    text = _document_text(rendered)
    footer = "\n".join(paragraph.text for paragraph in rendered.sections[0].footer.paragraphs)

    assert "October 8, 2026" in text
    assert "Automatically generated by PRISM" in footer
    assert "CONFIDENTIAL DOCUMENT" in footer
    assert "Page" in footer
    assert " of " in footer


@pytest.mark.skipif(shutil.which("soffice") is None, reason="LibreOffice is not installed")
def test_indonesian_pdf_preserves_localized_footer(tmp_path: Path) -> None:
    assessment = create_canonical_ale_assessment_data()
    source = tmp_path / "report-id.docx"
    source.write_bytes(generate_ale_review_docx(assessment, language="id"))
    pdf_path = convert_docx_to_pdf(source, tmp_path)
    pdf = PdfReader(pdf_path)
    text = "\n".join(page.extract_text() or "" for page in pdf.pages)

    assert "DOKUMEN RAHASIA" in text
    assert "Halaman" in text
    assert "CONFIDENTIAL DOCUMENT" not in text
