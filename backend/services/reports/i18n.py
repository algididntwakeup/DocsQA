def _locale(language: ReportLanguage | str) -> str:
    value = getattr(language, "value", language)
    return "id" if str(value).lower() == "id" else "en"


def get_report_labels(language: ReportLanguage | str) -> dict[str, dict[str, str]]:
    """Return the fixed report-label catalog for a validated or string locale."""
    return REPORT_LABELS[_locale(language)]


def translate_severity(value: Any, language: ReportLanguage | str) -> str:
    """Translate a severity enum or value to its reader-facing report label."""
    raw = str(getattr(value, "value", value) or "").strip().upper().replace("-", "_")
    if not raw:
        return ""
    labels = get_report_labels(language)["severity"]
    return labels.get(raw, raw.replace("_", " ").title())


def translate_status(value: Any, language: ReportLanguage | str) -> str:
    """Translate compliance and workflow status enums for report display."""
    raw = str(getattr(value, "value", value) or "").strip().upper().replace("-", "_")
    if not raw:
        return ""
    labels = get_report_labels(language)
    translated = labels["compliance"].get(raw) or labels["status"].get(raw)
    return translated or raw.replace("_", " ").title()


def localize_report_tokens(value: str, language: ReportLanguage | str) -> str:
    """Translate known enum tokens embedded in report headings and generated labels."""
    labels = get_report_labels(language)
    mapping = {
        **labels["severity"],
        **labels["compliance"],
        **labels["status"],
        **labels["category"],
    }
    token_pattern = "|".join(sorted(map(re.escape, mapping), key=len, reverse=True))
    pattern = re.compile(rf"\b({token_pattern})\b")
    return pattern.sub(lambda match: mapping[match.group(0)], value)


def localize_review_score(value: str, language: ReportLanguage | str) -> str:
    """Localize a legacy machine-readable score banner for Indonesian reports."""
    if _locale(language) == "en" or not value:
        return value
    labels = get_report_labels(language)["score"]
    localized = value.replace("REVIEWSCORE", labels["label"])
    for key in ("document", "revision", "date", "baseline", "blockers", "majors", "minors"):
        english_key = {"document": "doc", "revision": "rev"}.get(key, key)
        localized = re.sub(rf"\b{english_key}=", f"{labels[key]}=", localized)
    localized = re.sub(r"\bnot supplied\b", labels["missing"], localized, flags=re.IGNORECASE)
    return re.sub(r"\bN/A\b", labels["not_applicable"], localized)
